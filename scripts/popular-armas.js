function buildCoC7WeaponItem(wp, folderId) {
  let normalUses = "1";
  let maxUses = "";
  if (wp.uses.includes("(")) {
    const parts = wp.uses.split("(");
    normalUses = parts[0].trim();
    maxUses = parts[1].replace(/\D/g, "");
  } else if (wp.uses === "1 ou 2") {
    normalUses = "1";
    maxUses = "2";
  } else {
    normalUses = wp.uses;
  }

  const descParts = [
    `<p><strong>Perícia:</strong> ${wp.skill}</p>`,
    `<p><strong>Dano:</strong> ${wp.damage}${wp.addb ? " + DX" : ""}${wp.ahdb ? " + meio DX" : ""}${wp.damageLong ? ` / ${wp.damageLong} / ${wp.damageExtreme}` : ""}</p>`,
    `<p><strong>Alcance Base:</strong> ${wp.range}${wp.rangeLong ? `/${wp.rangeLong}/${wp.rangeExtreme}` : ""} ${!isNaN(Number(wp.range)) ? "metros" : ""}</p>`,
    `<p><strong>Usos por Rodada:</strong> ${wp.uses}</p>`,
    `<p><strong>Munição na Arma:</strong> ${wp.bullets || "-"}</p>`,
    `<p><strong>Custo (1920s / Moderna):</strong> ${wp.price20s} / ${wp.priceModern}</p>`,
    `<p><strong>Defeito:</strong> ${wp.malfunction ?? "-"}</p>`
  ];
  if (wp.notes) {
    descParts.push(`<p><strong>Notas:</strong> ${wp.notes}</p>`);
  }

  return {
    name: wp.name,
    type: "weapon",
    folder: folderId,
    system: {
      skill: {
        main: { name: wp.skill }
      },
      range: {
        normal: {
          value: !isNaN(Number(wp.range)) ? Number(wp.range) : 0,
          units: "m",
          damage: wp.damage
        },
        long: {
          value: wp.rangeLong ? Number(wp.rangeLong) : 0,
          units: "m",
          damage: wp.damageLong || ""
        },
        extreme: {
          value: wp.rangeExtreme ? Number(wp.rangeExtreme) : 0,
          units: "m",
          damage: wp.damageExtreme || ""
        }
      },
      bullets: wp.bullets || "",
      malfunction: wp.malfunction ?? null,
      usesPerRound: {
        normal: normalUses,
        max: maxUses,
        burst: wp.burstSize || ""
      },
      price: {
        "1920": wp.price20s || "",
        modern: wp.priceModern || ""
      },
      era: {
        "1920": !!wp.era20s,
        modern: !!wp.eraModern
      },
      properties: {
        melee: !!wp.melee,
        rngd: !!wp.rngd,
        thrown: !!wp.thrown,
        addb: !!wp.addb,
        ahdb: !!wp.ahdb,
        impl: !!wp.impl,
        shotgun: !!wp.shotgun,
        auto: !!wp.auto,
        brst: !!wp.brst,
        stun: !!wp.stun,
        burn: !!wp.burn,
        rare: !!wp.rare
      },
      description: {
        value: descParts.join("")
      }
    }
  };
}

async function popularCompendioArmas() {
  const pack = game.packs.get("coc7-armas-compendio.armas");
  if (!pack) {
    return ui.notifications.error("Compêndio 'coc7-armas-compendio.armas' não encontrado!");
  }

  const wasLocked = pack.locked;
  if (wasLocked) await pack.configure({ locked: false });

  const folderMap = {};
  for (const [folderName, color] of Object.entries(FOLDER_COLORS)) {
    let f = pack.folders.find(fl => fl.name === folderName);
    if (!f) {
      f = await Folder.create(
        { name: folderName, type: "Item", color },
        { pack: pack.collection }
      );
    }
    folderMap[folderName] = f.id;
  }

  await pack.getIndex();

  let criadas = 0;
  for (const wp of WEAPONS_DATA) {
    if (pack.index.find(i => i.name === wp.name)) continue;
    const itemData = buildCoC7WeaponItem(wp, folderMap[wp.folder]);
    await Item.create(itemData, { pack: pack.collection });
    criadas++;
  }

  if (wasLocked) await pack.configure({ locked: true });
  if (criadas > 0) {
    ui.notifications.info(`[Armas CoC7] ${criadas} armas adicionadas e organizadas em pastas!`);
  }
}

Hooks.once("ready", async () => {
  if (!game.user.isGM) return;

  window.CoC7ArmasCompendio = {
    popularArmas: popularCompendioArmas
  };

  const pack = game.packs.get("coc7-armas-compendio.armas");
  if (pack) {
    await pack.getIndex();
    if (pack.index.size < WEAPONS_DATA.length) {
      await popularCompendioArmas();
    }
  }
});